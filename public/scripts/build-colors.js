#!/usr/bin/env node
// scripts/build-colors.js
//
// Reads colors.json, merges duplicate hexes, and writes colors-data.js
// (a global that pages consume via window.COLOR_NAMES_DATA).
//
// Does NOT write any HTML — pages are built by build-pages.js.

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC_JSON = path.join(ROOT, "colors.json");
const OUT_JS = path.join(ROOT, "colors-data.js");

function log(...a) { console.log("[build-colors]", ...a); }

if (!fs.existsSync(SRC_JSON)) {
  console.error("Missing colors.json at", SRC_JSON);
  process.exit(1);
}

log("Reading", path.relative(ROOT, SRC_JSON));
const raw = JSON.parse(fs.readFileSync(SRC_JSON, "utf8"));

// -------- Normalize and merge duplicates --------
// Key by hex. Merge name lists, deduplicate by (name, source).
const byHex = new Map();

function normalizeName(n) {
  const m = /^(.*?)\s*\(([^()]+)\)\s*$/.exec(n.name || "");
  if (m) return { name: m[1].trim(), source: (n.source || m[2]).trim() };
  return { name: (n.name || "").trim(), source: (n.source || "Unknown").trim() };
}

for (const entry of raw) {
  const hex = String(entry.hex || "").replace(/^#/, "").toUpperCase();
  if (!/^[0-9A-F]{6}$/.test(hex)) {
    console.warn("  skipping invalid hex:", entry.hex);
    continue;
  }
  if (!byHex.has(hex)) byHex.set(hex, new Map());
  const names = byHex.get(hex);
  for (const n of entry.names || []) {
    const { name, source } = normalizeName(n);
    if (!name) continue;
    const key = `${name}||${source}`;
    if (!names.has(key)) names.set(key, { name, source });
  }
}

const merged = Array.from(byHex.entries())
  .map(([hex, namesMap]) => ({
    hex,
    names: Array.from(namesMap.values()).sort((a, b) =>
      a.name.localeCompare(b.name)
    ),
  }))
  .sort((a, b) => a.hex.localeCompare(b.hex));

const totalNames = merged.reduce((s, c) => s + c.names.length, 0);
log(`Merged to ${merged.length} hexes, ${totalNames} names`);

// -------- Write colors-data.js --------
const jsContent =
  "// Generated by scripts/build-colors.js — do not edit by hand.\n" +
  "// Source: colors.json\n" +
  "window.COLOR_NAMES_DATA = " +
  JSON.stringify(merged).replace(/</g, "\\u003c").replace(/>/g, "\\u003e") +
  ";\n";

fs.writeFileSync(OUT_JS, jsContent);
log(`Wrote ${path.relative(ROOT, OUT_JS)} (${(Buffer.byteLength(jsContent) / 1024).toFixed(1)} KB)`);